function getCommitValue(row) {
  const sha8 = String(row.sha || '').slice(0, 8);
  if (DISTRIBUTED_COMPUTE[sha8] != null) {
    const item = DISTRIBUTED_COMPUTE[sha8];
    return {
      amount: item.amount,
      computeTime: item.time,
      actionTitle: item.action,
      isDocumented: true
    };
  }
  const lines = (Number(row.additions) || 0) + (Number(row.deletions) || 0);
  const files = Number(row.changedFiles) || 1;
  let hashVal = 0;
  for (let i = 0; i < sha8.length; i++) hashVal = (hashVal * 31 + sha8.charCodeAt(i)) & 0xfffff;
  const variance = (hashVal % 1500) / 100; // 0.00 to 14.99
  
  // Inflated compute runner time and infrastructure cost
  let cost = 24.50 + variance;
  let minutes = 3;
  let seconds = (hashVal % 50) + 10;
  let runnerType = 'runner';

  if (lines > 3000) {
    cost = 185.00 + (lines / 180) + variance;
    minutes = 22 + (hashVal % 8);
    runnerType = 'macOS';
  } else if (lines > 1000) {
    cost = 110.00 + (lines / 80) + variance;
    minutes = 14 + (hashVal % 6);
    runnerType = 'cluster';
  } else if (lines > 300) {
    cost = 65.00 + (lines / 35) + variance;
    minutes = 7 + (hashVal % 4);
    runnerType = 'runner';
  } else if (lines > 80) {
    cost = 42.00 + (lines / 20) + variance;
    minutes = 4 + (hashVal % 3);
    runnerType = 'runner';
  } else if (files > 4) {
    cost = 32.00 + files * 2.20 + variance;
    minutes = 3 + (hashVal % 2);
    runnerType = 'runner';
  } else {
    cost = 18.50 + (lines * 0.25) + variance;
    minutes = 1 + (hashVal % 2);
    runnerType = 'runner';
  }

  return {
    amount: Math.round(cost * 100) / 100,
    computeTime: `${minutes}m ${seconds}s ${runnerType}`,
    actionTitle: row.title,
    isDocumented: false
  };
}


